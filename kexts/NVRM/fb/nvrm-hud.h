static inline void hudFill(volatile unsigned int *px, unsigned ppr,
                           int x, int y, int w, int h, unsigned int c)
{
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    for (int j = 0; j < h; j++) {
        volatile unsigned int *row = px + (unsigned long)(y + j) * ppr;
        for (int i = 0; i < w; i++) row[x + i] = c;
    }
}

static inline int hudText(volatile unsigned int *px, unsigned ppr,
                          int x, int y, int s, unsigned int fg, const char *str)
{
    for (const char *p = str; *p; p++) {
        int c = (unsigned char)*p;
        if (c >= 'a' && c <= 'z') c -= 32;
        if (c < HUD_FONT_LO || c > HUD_FONT_HI) c = ' ';
        const unsigned char *gl = kHudFont[c - HUD_FONT_LO];
        for (int gy = 0; gy < 7; gy++) {
            unsigned char bits = gl[gy];
            for (int gx = 0; gx < 5; gx++) {
                if (!(bits & (0x10 >> gx))) continue;
                hudFill(px, ppr, x + gx * s, y + gy * s, s, s, fg);
            }
        }
        x += 6 * s;
    }
    return x;
}
